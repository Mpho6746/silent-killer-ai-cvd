def get_translator(lang_code):
    """Returns a t(key) function for the given language, falling back to English."""
    strings = TRANSLATIONS.get(lang_code, TRANSLATIONS["en"])

    def t(key):
        return strings.get(key, TRANSLATIONS["en"][key])

    return t
